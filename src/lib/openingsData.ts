/**
 * Matches the most specific opening in the database based on the played SAN moves.
 */
export function matchOpeningFromMoves(playedSanMoves: string[]): OpeningInfo | undefined {
  if (!playedSanMoves || playedSanMoves.length === 0) return undefined;

  let bestMatch: OpeningInfo | undefined = undefined;
  let maxMatchedPlies = 0;

  for (const opening of OPENINGS_DATABASE) {
    const tokens = opening.moves
      .replace(/\d+\./g, '')
      .trim()
      .split(/\s+/)
      .filter(Boolean);

    if (tokens.length > playedSanMoves.length) continue;

    const matches = tokens.every((token, idx) => playedSanMoves[idx] === token);
    if (matches && tokens.length > maxMatchedPlies) {
      maxMatchedPlies = tokens.length;
      bestMatch = opening;
    }
  }

  return bestMatch;
}
